import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const content = [
"'use client';",
"",
"import { useState, useRef } from 'react';",
"import { Button } from '@/components/ui/button';",
"import { Input } from '@/components/ui/input';",
"import { Avatar, AvatarFallback, AvatarImage } from '@/components/ui/avatar';",
"import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuSeparator, DropdownMenuTrigger } from '@/components/ui/dropdown-menu';",
"import { EntryCard } from '@/components/EntryCard';",
"import { EntryForm } from '@/components/EntryForm';",
"import { PasswordGenerator } from '@/components/PasswordGenerator';",
"import { SecurityCenter } from '@/components/SecurityCenter';",
"import { Logo } from '@/components/Logo';",
"import { PasswordEntry } from '@/types/vault';",
"import { useVault } from '@/contexts/VaultContext';",
"import { useAuth } from '@/contexts/AuthContext';",
"import { useToast } from '@/components/ui/use-toast';",
"import { Search, Plus, Download, Upload, Lock, Shield, LogOut, User, Settings, Star, Layers, Clock, Wand2, ShieldAlert, ChevronRight } from 'lucide-react';",
"",
"type SidebarView = 'all' | 'favorites' | 'category' | 'recent' | 'generator' | 'security';",
"",
"export function VaultInterface() {",
"  const [sidebarView, setSidebarView] = useState<SidebarView>('all');",
"  const [activeCategory, setActiveCategory] = useState<string>('');",
"  const [entryFormOpen, setEntryFormOpen] = useState(false);",
"  const [editingEntry, setEditingEntry] = useState<PasswordEntry | undefined>();",
"  const fileInputRef = useRef<HTMLInputElement>(null);",
"",
"  const { vault, searchQuery, setSearchQuery, setSelectedCategory, getFilteredEntries, getCategories, exportVault, importVault, lockVault } = useVault();",
"  const { user, signOut } = useAuth();",
"  const { toast } = useToast();",
"",
"  const filteredEntries = getFilteredEntries();",
"  const categories = getCategories();",
"  const totalEntries = vault?.entries.length ?? 0;",
"  const favoriteCount = vault?.entries.filter((e) => e.isFavorite).length ?? 0;",
"",
"  const handleExport = async () => {",
"    try {",
"      const data = await exportVault();",
"      const blob = new Blob([data], { type: 'application/json' });",
"      const url = URL.createObjectURL(blob);",
"      const a = document.createElement('a');",
"      a.href = url;",
"      a.download = `securevoult-backup-${new Date().toISOString().split('T')[0]}.json`;",
"      document.body.appendChild(a);",
"      a.click();",
"      document.body.removeChild(a);",
"      URL.revokeObjectURL(url);",
"      toast({ title: 'Vault exported', description: 'Backup downloaded.' });",
"    } catch {",
"      toast({ title: 'Export failed', variant: 'destructive' });",
"    }",
"  };",
"",
"  const handleFileImport = async (e: React.ChangeEvent<HTMLInputElement>) => {",
"    const file = e.target.files?.[0];",
"    if (!file) return;",
"    try {",
"      const text = await file.text();",
"      await importVault(text);",
"      toast({ title: 'Vault imported', description: 'Backup restored successfully.' });",
"    } catch (err) {",
"      toast({ title: 'Import failed', description: err instanceof Error ? err.message : 'Invalid file.', variant: 'destructive' });",
"    }",
"    if (fileInputRef.current) fileInputRef.current.value = '';",
"  };",
"",
"  const handleSidebarNav = (view: SidebarView, category?: string) => {",
"    setSidebarView(view);",
"    if (view === 'favorites') { setSelectedCategory('all'); setSearchQuery(''); }",
"    else if (view === 'category' && category) { setActiveCategory(category); setSelectedCategory(category); }",
"    else if (view === 'all' || view === 'recent') { setSelectedCategory('all'); setSearchQuery(''); }",
"  };",
"",
"  const handleSignOut = async () => {",
"    try { await signOut(); }",
"    catch { toast({ title: 'Sign out failed', variant: 'destructive' }); }",
"  };",
"",
"  const getUserInitials = (name?: string | null, email?: string | null) => {",
"    if (name) return name.split(' ').map((n) => n[0]).join('').toUpperCase().slice(0, 2);",
"    if (email) return email.slice(0, 2).toUpperCase();",
"    return 'U';",
"  };",
"",
"  const displayedEntries = (() => {",
"    let entries = filteredEntries;",
"    if (sidebarView === 'favorites') entries = entries.filter((e) => e.isFavorite);",
"    if (sidebarView === 'recent') {",
"      entries = [...entries].sort((a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime()).slice(0, 10);",
"    }",
"    return entries;",
"  })();",
"",
"  const NavItem = ({ id, icon: Icon, label, count, category }: {",
"    id: SidebarView; icon: React.ElementType; label: string; count?: number; category?: string;",
"  }) => {",
"    const active = sidebarView === id && (id !== 'category' || activeCategory === category);",
"    return (",
"      <button",
"        onClick={() => handleSidebarNav(id, category)}",
"        className={`w-full flex items-center justify-between px-3 py-2 rounded-lg text-sm transition-colors ${",
"          active ? 'bg-primary/15 text-primary font-medium' : 'text-muted-foreground hover:text-foreground hover:bg-secondary/60'",
"        }`}",
"      >",
"        <div className=\"flex items-center gap-2.5\"><Icon className=\"w-4 h-4\" /><span>{label}</span></div>",
"        {count !== undefined && count > 0 && (",
"          <span className={`text-xs px-1.5 py-0.5 rounded-md ${active ? 'bg-primary/20 text-primary' : 'bg-secondary text-muted-foreground'}`}>{count}</span>",
"        )}",
"      </button>",
"    );",
"  };",
"",
"  const showEntryList = ['all', 'favorites', 'recent', 'category'].includes(sidebarView);",
"",
"  return (",
"    <div className=\"flex h-screen bg-background overflow-hidden\">",
"      {/* Sidebar */}",
"      <aside className=\"w-60 flex-shrink-0 border-r border-border flex flex-col bg-[hsl(222_40%_7%)]\">",
"        <div className=\"px-4 py-5 border-b border-border/50\"><Logo size=\"sm\" /></div>",
"        <nav className=\"flex-1 p-3 space-y-1 overflow-y-auto\">",
"          <div className=\"space-y-0.5\">",
"            <NavItem id=\"all\" icon={Layers} label=\"All items\" count={totalEntries} />",
"            <NavItem id=\"favorites\" icon={Star} label=\"Favorites\" count={favoriteCount} />",
"            <NavItem id=\"recent\" icon={Clock} label=\"Recently used\" />",
"          </div>",
"          {categories.length > 0 && (",
"            <div className=\"pt-4\">",
"              <p className=\"px-3 mb-1.5 text-xs font-semibold text-muted-foreground/60 uppercase tracking-wider\">Categories</p>",
"              <div className=\"space-y-0.5\">",
"                {categories.map((cat) => <NavItem key={cat} id=\"category\" icon={Layers} label={cat} category={cat} />)}",
"              </div>",
"            </div>",
"          )}",
"          <div className=\"pt-4\">",
"            <p className=\"px-3 mb-1.5 text-xs font-semibold text-muted-foreground/60 uppercase tracking-wider\">Tools</p>",
"            <div className=\"space-y-0.5\">",
"              <NavItem id=\"generator\" icon={Wand2} label=\"Password generator\" />",
"              <NavItem id=\"security\" icon={ShieldAlert} label=\"Security center\" />",
"            </div>",
"          </div>",
"        </nav>",
"        <div className=\"p-3 border-t border-border/50\">",
"          <DropdownMenu>",
"            <DropdownMenuTrigger asChild>",
"              <button className=\"w-full flex items-center gap-2.5 px-2 py-2 rounded-lg hover:bg-secondary/60 transition-colors text-left\">",
"                <Avatar className=\"h-7 w-7\">",
"                  <AvatarImage src={user?.photoURL || undefined} />",
"                  <AvatarFallback className=\"bg-primary/20 text-primary text-xs\">{getUserInitials(user?.displayName, user?.email)}</AvatarFallback>",
"                </Avatar>",
"                <div className=\"flex-1 min-w-0\">",
"                  <p className=\"text-xs font-medium truncate\">{user?.displayName || user?.email}</p>",
"                  {user?.displayName && <p className=\"text-xs text-muted-foreground truncate\">{user.email}</p>}",
"                </div>",
"                <ChevronRight className=\"w-3 h-3 text-muted-foreground flex-shrink-0\" />",
"              </button>",
"            </DropdownMenuTrigger>",
"            <DropdownMenuContent align=\"end\" className=\"w-48\">",
"              <DropdownMenuItem disabled><User className=\"mr-2 h-4 w-4\" />Profile</DropdownMenuItem>",
"              <DropdownMenuItem disabled><Settings className=\"mr-2 h-4 w-4\" />Settings</DropdownMenuItem>",
"              <DropdownMenuSeparator />",
"              <DropdownMenuItem onClick={handleExport}><Download className=\"mr-2 h-4 w-4\" />Export vault</DropdownMenuItem>",
"              <DropdownMenuItem onClick={() => fileInputRef.current?.click()}><Upload className=\"mr-2 h-4 w-4\" />Import vault</DropdownMenuItem>",
"              <DropdownMenuSeparator />",
"              <DropdownMenuItem onClick={() => lockVault()}><Lock className=\"mr-2 h-4 w-4\" />Lock vault</DropdownMenuItem>",
"              <DropdownMenuItem onClick={handleSignOut} className=\"text-destructive focus:text-destructive\"><LogOut className=\"mr-2 h-4 w-4\" />Sign out</DropdownMenuItem>",
"            </DropdownMenuContent>",
"          </DropdownMenu>",
"        </div>",
"      </aside>",
"",
"      {/* Main */}",
"      <div className=\"flex-1 flex flex-col min-w-0\">",
"        <header className=\"flex-shrink-0 h-14 border-b border-border flex items-center gap-3 px-5\">",
"          <div className=\"relative flex-1 max-w-md\">",
"            <Search className=\"absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-muted-foreground pointer-events-none\" />",
"            <Input placeholder=\"Search your vault...\" value={searchQuery} onChange={(e) => setSearchQuery(e.target.value)} className=\"pl-9 h-9 bg-secondary/50 border-border/60 focus:border-primary text-sm\" />",
"          </div>",
"          <div className=\"ml-auto\">",
"            {showEntryList && (",
"              <Button size=\"sm\" className=\"h-9 bg-primary hover:bg-primary/90 text-primary-foreground\" onClick={() => { setEditingEntry(undefined); setEntryFormOpen(true); }}>",
"                <Plus className=\"w-4 h-4 mr-1.5\" />Add entry",
"              </Button>",
"            )}",
"          </div>",
"        </header>",
"",
"        <main className=\"flex-1 overflow-y-auto p-5\">",
"          {sidebarView === 'all' && totalEntries > 0 && (",
"            <div className=\"grid grid-cols-3 gap-3 mb-6\">",
"              {[",
"                { label: 'Total passwords', value: totalEntries, color: 'text-blue-400' },",
"                { label: 'Favorites', value: favoriteCount, color: 'text-yellow-400' },",
"                { label: 'Categories', value: categories.length, color: 'text-violet-400' },",
"              ].map(({ label, value, color }) => (",
"                <div key={label} className=\"bg-card border border-border rounded-xl p-4\">",
"                  <p className={`text-2xl font-bold ${color}`}>{value}</p>",
"                  <p className=\"text-xs text-muted-foreground mt-0.5\">{label}</p>",
"                </div>",
"              ))}",
"            </div>",
"          )}",
"",
"          {sidebarView === 'generator' && <PasswordGenerator />}",
"          {sidebarView === 'security' && <SecurityCenter />}",
"",
"          {showEntryList && (",
"            <>",
"              <div className=\"flex items-center justify-between mb-4\">",
"                <h2 className=\"text-sm font-semibold text-muted-foreground uppercase tracking-wider\">",
"                  {sidebarView === 'all' && 'All items'}",
"                  {sidebarView === 'favorites' && 'Favorites'}",
"                  {sidebarView === 'recent' && 'Recently used'}",
"                  {sidebarView === 'category' && activeCategory}",
"                  {displayedEntries.length > 0 && (",
"                    <span className=\"ml-2 normal-case font-normal text-muted-foreground/60\">{displayedEntries.length}</span>",
"                  )}",
"                </h2>",
"                {searchQuery && <button onClick={() => setSearchQuery('')} className=\"text-xs text-muted-foreground hover:text-foreground\">Clear</button>}",
"              </div>",
"              {displayedEntries.length > 0 ? (",
"                <div className=\"space-y-1.5\">",
"                  {displayedEntries.map((entry) => (",
"                    <EntryCard key={entry.id} entry={entry} onEdit={() => { setEditingEntry(entry); setEntryFormOpen(true); }} />",
"                  ))}",
"                </div>",
"              ) : (",
"                <div className=\"flex flex-col items-center justify-center py-20 text-center\">",
"                  <div className=\"w-14 h-14 rounded-2xl bg-secondary/50 flex items-center justify-center mb-4\">",
"                    <Shield className=\"w-6 h-6 text-muted-foreground/50\" />",
"                  </div>",
"                  <h3 className=\"font-semibold mb-1\">{searchQuery ? 'No results' : 'No entries yet'}</h3>",
"                  <p className=\"text-sm text-muted-foreground mb-5\">{searchQuery ? `No matches for \"${searchQuery}\"` : 'Add your first password.'}</p>",
"                  {!searchQuery && <Button size=\"sm\" onClick={() => { setEditingEntry(undefined); setEntryFormOpen(true); }}><Plus className=\"w-4 h-4 mr-1.5\" />Add entry</Button>}",
"                </div>",
"              )}",
"            </>",
"          )}",
"        </main>",
"      </div>",
"",
"      <EntryForm",
"        entry={editingEntry}",
"        open={entryFormOpen}",
"        onOpenChange={(open) => { if (!open) { setEntryFormOpen(false); setEditingEntry(undefined); } }}",
"      />",
"      <input ref={fileInputRef} type=\"file\" accept=\".json\" onChange={handleFileImport} className=\"hidden\" />",
"    </div>",
"  );",
"}",
].join('\n');

writeFileSync(join(root, 'src/components/VaultInterface.tsx'), content, 'utf8');
console.log('VaultInterface written:', content.split('\n').length, 'lines');
