import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const content = [
"'use client';",
"",
"import { useState } from 'react';",
"import { Button } from '@/components/ui/button';",
"import { Badge } from '@/components/ui/badge';",
"import { AlertDialog, AlertDialogAction, AlertDialogCancel, AlertDialogContent, AlertDialogDescription, AlertDialogFooter, AlertDialogHeader, AlertDialogTitle } from '@/components/ui/alert-dialog';",
"import { PasswordEntry } from '@/types/vault';",
"import { useVault } from '@/contexts/VaultContext';",
"import { useToast } from '@/components/ui/use-toast';",
"import { Copy, Edit, Trash2, ExternalLink, Eye, EyeOff, Check, Star } from 'lucide-react';",
"import { formatDistanceToNow } from 'date-fns';",
"",
"interface EntryCardProps {",
"  entry: PasswordEntry;",
"  onEdit: (entry: PasswordEntry) => void;",
"}",
"",
"export function EntryCard({ entry, onEdit }: EntryCardProps) {",
"  const [showPassword, setShowPassword] = useState(false);",
"  const [deleteDialogOpen, setDeleteDialogOpen] = useState(false);",
"  const [copied, setCopied] = useState<string | null>(null);",
"  const { deleteEntry, updateEntry } = useVault();",
"  const { toast } = useToast();",
"",
"  const copyToClipboard = async (text: string, type: string) => {",
"    try {",
"      await navigator.clipboard.writeText(text);",
"      setCopied(type);",
"      setTimeout(() => setCopied(null), 2000);",
"      toast({ title: `${type} copied`, description: 'Clipboard will clear in 30s.' });",
"    } catch {",
"      toast({ title: 'Copy failed', variant: 'destructive' });",
"    }",
"  };",
"",
"  const handleDelete = async () => {",
"    try {",
"      await deleteEntry(entry.id);",
"      toast({ title: 'Entry deleted' });",
"    } catch {",
"      toast({ title: 'Delete failed', variant: 'destructive' });",
"    }",
"    setDeleteDialogOpen(false);",
"  };",
"",
"  const toggleFavorite = async () => {",
"    try {",
"      await updateEntry({ ...entry, isFavorite: !entry.isFavorite });",
"    } catch {",
"      toast({ title: 'Update failed', variant: 'destructive' });",
"    }",
"  };",
"",
"  const letter = (entry.website || entry.username || '?')[0].toUpperCase();",
"  const maskedPassword = '\u2022'.repeat(Math.min(entry.password.length, 16));",
"",
"  const gradients = [",
"    'from-blue-500 to-violet-600',",
"    'from-violet-500 to-pink-600',",
"    'from-emerald-500 to-teal-600',",
"    'from-orange-500 to-red-600',",
"    'from-cyan-500 to-blue-600',",
"  ];",
"  const gradient = gradients[letter.charCodeAt(0) % gradients.length];",
"",
"  return (",
"    <>",
"      <div className=\"group flex items-center gap-4 px-4 py-3 rounded-xl bg-card border border-border hover:border-border/80 hover:bg-card/80 transition-all\">",
"        {/* Letter avatar */}",
"        <div className={`w-10 h-10 rounded-xl bg-gradient-to-br ${gradient} flex items-center justify-center flex-shrink-0`}>",
"          <span className=\"text-sm font-bold text-white\">{letter}</span>",
"        </div>",
"",
"        {/* Title & username */}",
"        <div className=\"flex-1 min-w-0\">",
"          <div className=\"flex items-center gap-2\">",
"            <span className=\"font-medium text-sm truncate\">{entry.website}</span>",
"            {entry.isFavorite && <Star className=\"w-3 h-3 text-yellow-400 flex-shrink-0 fill-yellow-400\" />}",
"            <Badge variant=\"outline\" className=\"text-xs h-4 px-1.5 flex-shrink-0 hidden sm:flex\">{entry.category}</Badge>",
"          </div>",
"          <p className=\"text-xs text-muted-foreground truncate mt-0.5\">{entry.username}</p>",
"        </div>",
"",
"        {/* Password preview */}",
"        <div className=\"hidden md:flex items-center gap-1.5 flex-shrink-0\">",
"          <span className=\"font-mono text-xs text-muted-foreground tracking-widest\">",
"            {showPassword ? entry.password : maskedPassword}",
"          </span>",
"        </div>",
"",
"        {/* Updated time */}",
"        <span className=\"hidden lg:block text-xs text-muted-foreground/60 flex-shrink-0 w-24 text-right\">",
"          {formatDistanceToNow(new Date(entry.updatedAt), { addSuffix: true })}",
"        </span>",
"",
"        {/* Actions */}",
"        <div className=\"flex items-center gap-1 flex-shrink-0 opacity-0 group-hover:opacity-100 transition-opacity\">",
"          <Button",
"            variant=\"ghost\" size=\"sm\"",
"            className=\"h-8 w-8 p-0 text-muted-foreground hover:text-foreground\"",
"            onClick={() => copyToClipboard(entry.username, 'Username')}",
"            title=\"Copy username\"",
"          >",
"            {copied === 'Username' ? <Check className=\"w-3.5 h-3.5 text-green-400\" /> : <Copy className=\"w-3.5 h-3.5\" />}",
"          </Button>",
"          <Button",
"            variant=\"ghost\" size=\"sm\"",
"            className=\"h-8 w-8 p-0 text-muted-foreground hover:text-foreground\"",
"            onClick={() => copyToClipboard(entry.password, 'Password')}",
"            title=\"Copy password\"",
"          >",
"            {copied === 'Password' ? <Check className=\"w-3.5 h-3.5 text-green-400\" /> : <Copy className=\"w-3.5 h-3.5\" />}",
"          </Button>",
"          <Button",
"            variant=\"ghost\" size=\"sm\"",
"            className=\"h-8 w-8 p-0 text-muted-foreground hover:text-foreground\"",
"            onClick={() => setShowPassword(!showPassword)}",
"            title={showPassword ? 'Hide password' : 'Show password'}",
"          >",
"            {showPassword ? <EyeOff className=\"w-3.5 h-3.5\" /> : <Eye className=\"w-3.5 h-3.5\" />}",
"          </Button>",
"          {entry.url && (",
"            <Button",
"              variant=\"ghost\" size=\"sm\"",
"              className=\"h-8 w-8 p-0 text-muted-foreground hover:text-foreground\"",
"              onClick={() => window.open(entry.url, '_blank', 'noopener,noreferrer')}",
"              title=\"Open website\"",
"            >",
"              <ExternalLink className=\"w-3.5 h-3.5\" />",
"            </Button>",
"          )}",
"          <Button",
"            variant=\"ghost\" size=\"sm\"",
"            className=\"h-8 w-8 p-0 text-muted-foreground hover:text-foreground\"",
"            onClick={() => onEdit(entry)}",
"            title=\"Edit\"",
"          >",
"            <Edit className=\"w-3.5 h-3.5\" />",
"          </Button>",
"          <Button",
"            variant=\"ghost\" size=\"sm\"",
"            className=\"h-8 w-8 p-0 text-muted-foreground hover:text-destructive\"",
"            onClick={() => setDeleteDialogOpen(true)}",
"            title=\"Delete\"",
"          >",
"            <Trash2 className=\"w-3.5 h-3.5\" />",
"          </Button>",
"        </div>",
"      </div>",
"",
"      <AlertDialog open={deleteDialogOpen} onOpenChange={setDeleteDialogOpen}>",
"        <AlertDialogContent>",
"          <AlertDialogHeader>",
"            <AlertDialogTitle>Delete entry?</AlertDialogTitle>",
"            <AlertDialogDescription>",
"              This will permanently delete <strong>{entry.website}</strong> from your vault. This action cannot be undone.",
"            </AlertDialogDescription>",
"          </AlertDialogHeader>",
"          <AlertDialogFooter>",
"            <AlertDialogCancel>Cancel</AlertDialogCancel>",
"            <AlertDialogAction onClick={handleDelete} className=\"bg-destructive hover:bg-destructive/90\">Delete</AlertDialogAction>",
"          </AlertDialogFooter>",
"        </AlertDialogContent>",
"      </AlertDialog>",
"    </>",
"  );",
"}",
].join('\n');

writeFileSync(join(root, 'src/components/EntryCard.tsx'), content, 'utf8');
console.log('EntryCard written:', content.split('\n').length, 'lines');
