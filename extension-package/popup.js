// Extension popup entry point
import React from 'react';
import { createRoot } from 'react-dom/client';
import { ExtensionPopup } from '../src/components/ExtensionPopup';
import { AuthProvider } from '../src/contexts/AuthContext';
import { VaultProvider } from '../src/contexts/VaultContext';
import { allowKeyExport } from '../src/lib/vault-crypto';

// Keep the unlocked key in the background worker's memory-only session
// storage, so the popup and the autofill menu don't ask again until auto-lock.
allowKeyExport();
const session = {
  load: () => chrome.runtime.sendMessage({ action: 'session:get' }).catch(() => null),
  save: (s) => chrome.runtime.sendMessage({ action: 'session:set', session: s }).then(() => undefined),
  clear: () => chrome.runtime.sendMessage({ action: 'session:clear' }).then(() => undefined),
};
import { Toaster } from '../src/components/ui/toaster';
// CSS is loaded via popup.styles.css (generated by Tailwind CLI during build)
// Do NOT import globals.css here — @tailwind directives are not supported by esbuild

const container = document.getElementById('root');
if (container) {
  const root = createRoot(container);
  root.render(
    <React.StrictMode>
      <AuthProvider>
        <VaultProvider session={session}>
          <ExtensionPopup />
          <Toaster />
        </VaultProvider>
      </AuthProvider>
    </React.StrictMode>
  );
}